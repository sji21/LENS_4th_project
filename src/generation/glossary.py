# 긴 용어를 먼저 찾아야 "최우선변제권"이 "우선변제권"으로 잘리지 않는다.
_TERMS_LONGEST_FIRST = tuple(sorted(GLOSSARY, key=len, reverse=True))
_TERM_RE = re.compile("|".join(re.escape(term) for term in _TERMS_LONGEST_FIRST))


def find_glossary_spans(text: str) -> tuple[dict, ...]:
    """본문에 등장한 용어의 위치와 뜻을 돌려준다.

    반환 구간은 ``text``의 문자 인덱스이므로, **화면에 그대로 그릴 문자열**을
    넘겨야 한다. 마스킹 전 문자열로 계산하면 화면과 위치가 어긋난다.

    같은 용어가 여러 번 나오면 첫 번째만 표시한다. 한 문단에서 같은 낱말에
    같은 툴팁이 반복해서 붙으면 읽기 방해가 되기 때문이다.
    """

    if not text:
        return ()

    spans: list[dict] = []
    seen: set[str] = set()
    for match in _TERM_RE.finditer(text):
        term = match.group(0)
        if term in seen:
            continue
        seen.add(term)
        spans.append(
            {
                "term": term,
                "definition": GLOSSARY[term],
                "start": match.start(),
                "end": match.end(),
            }
        )
    return tuple(spans)
